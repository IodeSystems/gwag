package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// Service definitions for `gwag service install`: a systemd user unit
// on Linux, a LaunchAgent on macOS. Rendering is pure so tests run on
// any OS.

const (
	svcDefaultName = "gwag"
	// launchd label prefix; the label is also the plist file name.
	svcLabelPrefix = "com.iodesystems."
	// Extra time on top of the gateway's own shutdown budget for
	// gRPC GracefulStop and cluster close.
	svcStopMargin = 30 * time.Second
)

type svcUnit struct {
	Name        string
	Exec        string   // absolute path to gwag
	DataDir     string   // --data-dir of `gwag up`
	Args        []string // passed to `gwag up` after --data-dir
	Env         []string // KEY=VALUE
	StopTimeout time.Duration
}

func (u svcUnit) unitFileName() string  { return u.Name + ".service" }
func (u svcUnit) label() string         { return svcLabelPrefix + u.Name }
func (u svcUnit) plistFileName() string { return u.label() + ".plist" }

// upArgs is the argument list after the executable. The unit runs from
// $HOME, so `up` must not write ./.gw/credentials.json; `service login`
// writes the context instead.
func (u svcUnit) upArgs() []string {
	a := []string{"up", "--data-dir", u.DataDir}
	if flagValue(u.Args, "--data-dir") == "" && !hasFlag(u.Args, "--no-context-write") {
		a = append(a, "--no-context-write")
	}
	return append(a, u.Args...)
}

// svcStopTimeout sizes TimeoutStopSec from the gateway's drain
// sequence (httpserve.go): stream drain (timeout), delay, in-flight
// wait (timeout), plus a margin for teardown.
func svcStopTimeout(args []string) time.Duration {
	timeout, delay := 30*time.Second, 5*time.Second
	if v := flagValue(args, "--shutdown-timeout"); v != "" {
		if d, err := time.ParseDuration(v); err == nil && d > 0 {
			timeout = d
		}
	}
	if v := flagValue(args, "--shutdown-delay"); v != "" {
		if d, err := time.ParseDuration(v); err == nil && d >= 0 {
			delay = d
		}
	}
	return 2*timeout + delay + svcStopMargin
}

// flagValue finds "--name value" or "--name=value" in an arg list.
func flagValue(args []string, name string) string {
	for i, a := range args {
		if a == name && i+1 < len(args) {
			return args[i+1]
		}
		if v, ok := strings.CutPrefix(a, name+"="); ok {
			return v
		}
	}
	return ""
}

func hasFlag(args []string, name string) bool {
	for _, a := range args {
		if a == name || strings.HasPrefix(a, name+"=") {
			return true
		}
	}
	return false
}

// sdQuote renders one word for a systemd Exec line. systemd unquotes
// itself, and expands % and $.
func sdQuote(s string) string {
	if s != "" && !strings.ContainsAny(s, " \t\"'\\$%;") {
		return s
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `%`, `%%`, `$`, `$$`)
	return `"` + r.Replace(s) + `"`
}

func (u svcUnit) renderSystemd() string {
	var b strings.Builder
	b.WriteString("# Generated by `gwag service install`. Edits are overwritten on reinstall.\n")
	fmt.Fprintf(&b, "[Unit]\nDescription=gwag gateway (%s)\n\n", u.Name)
	// Type=notify: active only after the gateway sends READY=1, which
	// is once it serves and /health is 200.
	b.WriteString("[Service]\nType=notify\n")
	parts := []string{sdQuote(u.Exec)}
	for _, a := range u.upArgs() {
		parts = append(parts, sdQuote(a))
	}
	fmt.Fprintf(&b, "ExecStart=%s\n", strings.Join(parts, " "))
	for _, e := range u.Env {
		fmt.Fprintf(&b, "Environment=%s\n", sdQuote(e))
	}
	b.WriteString("Restart=on-failure\nRestartSec=2\n")
	// SIGTERM to the gateway only; stragglers get SIGKILL after the
	// stop timeout.
	b.WriteString("KillMode=mixed\n")
	b.WriteString("TimeoutStartSec=120\n")
	fmt.Fprintf(&b, "TimeoutStopSec=%d\n", int(u.StopTimeout.Seconds()))
	b.WriteString("\n[Install]\nWantedBy=default.target\n")
	return b.String()
}

func xmlEscape(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;", "'", "&apos;").Replace(s)
}

func (u svcUnit) renderPlist(logPath string) string {
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by ` + "`gwag service install`" + `. Edits are overwritten on reinstall. -->
<plist version="1.0">
<dict>
`)
	kv := func(k, v string) { fmt.Fprintf(&b, "\t<key>%s</key>\n\t<string>%s</string>\n", k, xmlEscape(v)) }
	kv("Label", u.label())
	b.WriteString("\t<key>ProgramArguments</key>\n\t<array>\n")
	for _, a := range append([]string{u.Exec}, u.upArgs()...) {
		fmt.Fprintf(&b, "\t\t<string>%s</string>\n", xmlEscape(a))
	}
	b.WriteString("\t</array>\n")
	if len(u.Env) > 0 {
		b.WriteString("\t<key>EnvironmentVariables</key>\n\t<dict>\n")
		for _, e := range u.Env {
			k, v, _ := strings.Cut(e, "=")
			fmt.Fprintf(&b, "\t\t<key>%s</key>\n\t\t<string>%s</string>\n", xmlEscape(k), xmlEscape(v))
		}
		b.WriteString("\t</dict>\n")
	}
	kv("StandardOutPath", logPath)
	kv("StandardErrorPath", logPath)
	// Start at login; restart after a failure, not after a clean exit
	// (same as Restart=on-failure).
	b.WriteString("\t<key>RunAtLoad</key>\n\t<true/>\n")
	b.WriteString("\t<key>KeepAlive</key>\n\t<dict>\n\t\t<key>SuccessfulExit</key>\n\t\t<false/>\n\t</dict>\n")
	b.WriteString("\t<key>ThrottleInterval</key>\n\t<integer>10</integer>\n")
	// launchd's default 20 s would SIGKILL a draining gateway.
	fmt.Fprintf(&b, "\t<key>ExitTimeOut</key>\n\t<integer>%d</integer>\n", int(u.StopTimeout.Seconds()))
	kv("ProcessType", "Interactive")
	b.WriteString("</dict>\n</plist>\n")
	return b.String()
}

// writeFileAtomic replaces path with data (tmp file, then rename), so
// a reinstall never leaves a half-written definition.
func writeFileAtomic(path string, data []byte, mode os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, mode); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
