func TestInstallIdempotent(t *testing.T) {
	env, _, _ := newTestEnv(t, "linux")
	read := func() string {
		b, err := os.ReadFile(env.defPath("gwag"))
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	if err := env.install([]string{"--", "--addr", ":1"}); err != nil {
		t.Fatal(err)
	}
	first := read()
	if err := env.install([]string{"--", "--addr", ":1"}); err != nil {
		t.Fatal(err)
	}
	if read() != first {
		t.Error("reinstall changed the unit")
	}
	if err := env.install([]string{"--", "--addr", ":2"}); err != nil {
		t.Fatal(err)
	}
	if got := read(); got == first || !strings.Contains(got, "--addr :2") || strings.Contains(got, "--addr :1") {
		t.Errorf("not overwritten:\n%s", got)
	}
}

