func TestDarwinInstallAndControl(t *testing.T) {
	env, f, _ := newTestEnv(t, "darwin")
	env.getenv = func(k string) string {
		if k == "PATH" {
			return "/opt/homebrew/bin:/usr/bin"
		}
		return ""
	}
	if err := env.install([]string{"--name", "m", "--enable", "--start", "--", "--addr", ":9"}); err != nil {
		t.Fatal(err)
	}
	p := filepath.Join(env.home, "Library/LaunchAgents/com.iodesystems.m.plist")
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(b), "/opt/homebrew/bin:/usr/bin") || !strings.Contains(string(b), "Library/Logs/gwag/m.log") {
		t.Errorf("plist:\n%s", b)
	}
	if !f.has("launchctl", "enable", "gui/1000/com.iodesystems.m") || !f.has("launchctl", "bootstrap", "gui/1000", p) {
		t.Errorf("calls %v", f.calls)
	}
	f.calls = nil
	f.loaded = true
	env.dispatch("start", []string{"--name", "m"})
	if !f.has("launchctl", "kickstart", "gui/1000/com.iodesystems.m") {
		t.Errorf("start: %v", f.calls)
	}
	if args, err := env.installedArgs("m"); err != nil || flagValue(args, "--addr") != ":9" {
		t.Errorf("installedArgs %v %v", args, err)
	}
	env.uid = 0
	if code := env.dispatch("start", nil); code != 1 {
		t.Errorf("root accepted: %d", code)
	}
}

func TestServiceMainAliasPrecedence(t *testing.T) {
	calls := stubNouns(t)
	for _, v := range legacyServiceVerbs {
		*calls = nil
		var out, errb bytes.Buffer
		code := serviceMain([]string{v, "--a"}, &out, &errb)
		if code != 7 || len(*calls) != 1 || (*calls)[0].noun != "services" {
			t.Errorf("%s: code=%d calls=%v", v, code, *calls)
		}
		if !strings.Contains(errb.String(), "moved to") {
			t.Errorf("%s: no moved warning: %q", v, errb.String())
		}
	}
	var out, errb bytes.Buffer
	if code := serviceMain([]string{"bogus"}, &out, &errb); code != 2 || !strings.Contains(errb.String(), "Usage:") {
		t.Errorf("bogus: %d %q", code, errb.String())
	}
	if code := serviceMain(nil, &out, &errb); code != 2 {
		t.Errorf("nil: %d", code)
	}
}

func TestLoginWritesContextWithoutPrintingToken(t *testing.T) {
	env, _, out := newTestEnv(t, "linux")
	t.Setenv("XDG_CONFIG_HOME", filepath.Join(env.home, "cfg"))
	if err := env.install([]string{"--name", "lg", "--", "--addr", "127.0.0.1:18780", "--control-plane", ":18781"}); err != nil {
		t.Fatal(err)
	}
	dd := env.installedDataDir("lg")
	const tok = "deadbeefdeadbeefdeadbeefdeadbeef"
	if err := os.WriteFile(filepath.Join(dd, "admin-token"), []byte(tok+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	out.Reset()
	if err := env.login([]string{"--name", "lg"}); err != nil {
		t.Fatal(err)
	}
	if strings.Contains(out.String(), tok) {
		t.Errorf("token printed: %q", out.String())
	}
	b, err := os.ReadFile(filepath.Join(env.home, "cfg", "gwag", "credentials.json"))
	if err != nil {
		t.Fatal(err)
	}
	var c credentials
	if err := json.Unmarshal(b, &c); err != nil {
		t.Fatal(err)
	}
	want := loginEntry{Name: "lg", Primary: true, Gateway: "localhost:18781", Endpoint: "http://127.0.0.1:18780", Bearer: tok}
	if len(c.Logins) != 1 || c.Logins[0] != want {
		t.Errorf("got %+v", c.Logins)
	}
	st, _ := os.Stat(filepath.Join(env.home, "cfg", "gwag", "credentials.json"))
	if st.Mode().Perm() != 0o600 {
		t.Errorf("mode %v", st.Mode())
	}
}

