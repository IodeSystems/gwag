func TestUninstallKeepsData(t *testing.T) {
	env, f, out := newTestEnv(t, "linux")
	if err := env.install([]string{"--name", "u"}); err != nil {
		t.Fatal(err)
	}
	out.Reset()
	if err := env.uninstall([]string{"--name", "u"}); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(env.defPath("u")); !os.IsNotExist(err) {
		t.Error("unit remains")
	}
	dd := filepath.Join(env.home, ".local/share/gwag/u")
	if _, err := os.Stat(dd); err != nil {
		t.Error("data dir removed")
	}
	if !strings.Contains(out.String(), dd) {
		t.Errorf("data dir not named: %q", out.String())
	}
	for _, c := range [][]string{{"--user", "stop", "u.service"}, {"--user", "disable", "u.service"}} {
		if !f.has("systemctl", c...) {
			t.Errorf("missing %v", c)
		}
	}
}

