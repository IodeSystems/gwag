func TestSdSplitRoundTrip(t *testing.T) {
	in := []string{"/a b/gwag", "up", `we"ird`, "100%", "$x"}
	var parts []string
	for _, a := range in {
		parts = append(parts, sdQuote(a))
	}
	if got := sdSplit(strings.Join(parts, " ")); !reflect.DeepEqual(got, []string{"/a b/gwag", "up", `we"ird`, "100%%", "$$x"}) {
		// % and $ are doubled for systemd; sdSplit leaves them as written.
		t.Errorf("got %q", got)
	}
}

func TestInstallLinux(t *testing.T) {
	env, f, out := newTestEnv(t, "linux")
	args := []string{"--name", "gwag-t", "--env", "A=b", "--enable", "--start", "--", "--addr", "127.0.0.1:18780"}
	if err := env.install(args); err != nil {
		t.Fatal(err, out.String())
	}
	unit := filepath.Join(env.home, ".config/systemd/user/gwag-t.service")
	b, err := os.ReadFile(unit)
	if err != nil {
		t.Fatal(err)
	}
	dd := filepath.Join(env.home, ".local/share/gwag/gwag-t")
	if !strings.Contains(string(b), "ExecStart=/opt/gwag/bin/gwag up --data-dir "+dd+" --no-context-write --addr 127.0.0.1:18780\n") {
		t.Errorf("unit:\n%s", b)
	}
	if !strings.Contains(string(b), "Environment=A=b\n") {
		t.Errorf("env missing:\n%s", b)
	}
	st, err := os.Stat(dd)
	if err != nil || st.Mode().Perm() != 0o700 {
		t.Errorf("data dir %v %v", st, err)
	}
	for _, c := range [][]string{{"--user", "daemon-reload"}, {"--user", "enable", "gwag-t.service"}, {"--user", "restart", "gwag-t.service"}} {
		if !f.has("systemctl", c...) {
			t.Errorf("missing systemctl %v; calls %v", c, f.calls)
		}
	}
}

