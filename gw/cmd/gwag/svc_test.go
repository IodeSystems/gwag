type svcCall struct {
	name string
	args []string
}

// testSvcEnv builds an env rooted in a temp home. systemd reachability
// and per-command failures are set through the returned fake.
type fakeRun struct {
	calls     []svcCall
	noSystemd bool
	loaded    bool // launchctl print result
}

func newTestEnv(t *testing.T, goos string) (*svcEnv, *fakeRun, *bytes.Buffer) {
	t.Helper()
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("XDG_CONFIG_HOME", "")
	t.Setenv("XDG_DATA_HOME", "")
	f := &fakeRun{}
	var out bytes.Buffer
	env := &svcEnv{
		out: &out, err: &out, goos: goos, uid: 1000, home: home,
		getenv: os.Getenv,
		exe:    func() (string, error) { return "/opt/gwag/bin/gwag", nil },
		sleep:  func(time.Duration) {},
		run: func(_, _ io.Writer, name string, args ...string) error {
			f.calls = append(f.calls, svcCall{name, args})
			if f.noSystemd && name == "systemctl" {
				return io.ErrClosedPipe
			}
			if name == "launchctl" && len(args) > 0 && args[0] == "print" && !f.loaded {
				return io.ErrClosedPipe
			}
			return nil
		},
	}
	return env, f, &out
}

func (f *fakeRun) has(name string, args ...string) bool {
	for _, c := range f.calls {
		if c.name == name && reflect.DeepEqual(c.args, args) {
			return true
		}
	}
	return false
}

func TestSystemdUnitText(t *testing.T) {
	u := svcUnit{Name: "gwag", Exec: "/opt/gwag/bin/gwag", DataDir: "/data/g w",
		Args: []string{"--addr", "127.0.0.1:18780"}, Env: []string{"A=b c"}, StopTimeout: 95 * time.Second}
	want := "# Generated by `gwag service install`. Edits are overwritten on reinstall.\n" +
		"[Unit]\nDescription=gwag gateway (gwag)\n\n" +
		"[Service]\nType=notify\n" +
		"ExecStart=/opt/gwag/bin/gwag up --data-dir \"/data/g w\" --no-context-write --addr 127.0.0.1:18780\n" +
		"Environment=\"A=b c\"\n" +
		"Restart=on-failure\nRestartSec=2\nKillMode=mixed\nTimeoutStartSec=120\nTimeoutStopSec=95\n\n" +
		"[Install]\nWantedBy=default.target\n"
	if got := u.renderSystemd(); got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

func TestPlistText(t *testing.T) {
	u := svcUnit{Name: "x", Exec: "/bin/gwag", DataDir: "/d", Args: []string{"--addr", ":1"},
		Env: []string{"K=v&"}, StopTimeout: 95 * time.Second}
	got := u.renderPlist("/log/x.log")
	for _, w := range []string{
		"<string>com.iodesystems.x</string>",
		"<string>/bin/gwag</string>\n\t\t<string>up</string>\n\t\t<string>--data-dir</string>\n\t\t<string>/d</string>\n\t\t<string>--no-context-write</string>",
		"<key>K</key>\n\t\t<string>v&amp;</string>",
		"<key>StandardOutPath</key>\n\t<string>/log/x.log</string>",
		"<key>SuccessfulExit</key>",
		"<key>ExitTimeOut</key>\n\t<integer>95</integer>",
	} {
		if !strings.Contains(got, w) {
			t.Errorf("plist lacks %q:\n%s", w, got)
		}
	}
	if !reflect.DeepEqual(plistArgs(got)[:3], []string{"/bin/gwag", "up", "--data-dir"}) {
		t.Errorf("plistArgs %v", plistArgs(got))
	}
}

