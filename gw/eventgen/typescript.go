// pinned versions the install hint names. Keep in step with
// ts/events/package.json and examples/events/ts/package.json.
const protocGenESVersion = "2.17.0"

const defaultEventsImport = "@gwag/events"

func init() {
	ts := &Language{Name: "ts", Plugins: tsPlugins, Emitter: EmitterFunc(emitTS)}
	alias := *ts
	alias.Name = "typescript"
	Register(ts)
	Register(&alias)
}

// tsParams splits --opt values into the ones for protoc-gen-es and
// the ones gwag reads itself (events_import=<module>).
type tsParams struct {
	plugin       []string
	eventsImport string
	importExt    string // "", ".js", ".ts"
	hasMapImport bool
}

func parseTSParams(param string) tsParams {
	p := tsParams{eventsImport: defaultEventsImport}
	for _, kv := range strings.Split(param, ",") {
		kv = strings.TrimSpace(kv)
		if kv == "" {
			continue
		}
		k, v, _ := strings.Cut(kv, "=")
		switch k {
		case "events_import":
			p.eventsImport = v
			continue
		case "import_extension":
			switch v {
			case "js":
				p.importExt = ".js"
			case "ts":
				p.importExt = ".ts"
			}
		case "map_imports":
			p.hasMapImport = true
		}
		p.plugin = append(p.plugin, kv)
	}
	return p
}

// tsPlugins resolves protoc-gen-es from the consumer's
// node_modules/.bin, never from PATH.
func tsPlugins(ctx context.Context, env Env) ([]Plugin, error) {
	bin := filepath.Join(env.ModuleDir, "node_modules", ".bin", "protoc-gen-es")
	p, err := ResolvePlugin(ctx, "protoc-gen-es", []string{bin}, env.ModuleDir,
		"pnpm add --save-dev --save-exact @bufbuild/protoc-gen-es@"+protocGenESVersion+" @bufbuild/protobuf@"+protocGenESVersion)
	if err != nil {
		return nil, err
	}
	tp := parseTSParams(env.Parameter)
	// gwag's option file (imported for the binding annotation) is
	// served by @gwag/events instead of being generated next to the
	// output.
	if !tp.hasMapImport {
		tp.plugin = append(tp.plugin, "map_imports=gw/proto/ps/:"+tp.eventsImport+"/proto")
	}
	p.Parameter = strings.Join(tp.plugin, ",")
	return []Plugin{p}, nil
}

// tsRef is an identifier to import.
type tsRef struct {
	module string // import specifier
	name   string
	typ    bool // only used as a type
}

// tsGen writes one <file>_events.ts.
type tsGen struct {
	dir       string // directory of the events file, slash separated
	params    tsParams
	imports   map[string]map[string]bool // module -> name -> type-only
	taken     map[string]string          // identifier -> what claimed it
	body      strings.Builder
	methods   strings.Builder
	chanCount int
}

func emitTS(in *Input) ([]*pluginpb.CodeGeneratorResponse_File, error) {
	if len(in.Channels) == 0 {
		return nil, nil
	}
	params := parseTSParams(in.Request.GetParameter())
	var order []string
	byFile := map[string][]*Channel{}
	for _, c := range in.Channels {
		p := c.File.Path()
		if _, ok := byFile[p]; !ok {
			order = append(order, p)
		}
		byFile[p] = append(byFile[p], c)
	}
	var out []*pluginpb.CodeGeneratorResponse_File
	for _, p := range order {
		name := strings.TrimSuffix(p, ".proto") + "_events.ts"
		content, err := tsFile(p, name, byFile[p], params, in.Header)
		if err != nil {
			return nil, err
		}
		out = append(out, &pluginpb.CodeGeneratorResponse_File{Name: &name, Content: &content})
	}
	return out, nil
}

func tsFile(protoPath, outName string, chans []*Channel, params tsParams, h Header) (string, error) {
	g := &tsGen{
		dir:     path.Dir(outName),
		params:  params,
		imports: map[string]map[string]bool{},
		taken:   map[string]string{"ev": "runtime import", "pb": "runtime import"},
	}
	bus := tsBusName(protoPath)
	if err := g.claim(bus, "bus class of "+protoPath); err != nil {
		return "", err
	}

	for _, c := range chans {
		if err := g.channel(c); err != nil {
			return "", err
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by gwag gen. DO NOT EDIT.\n// versions:\n")
	for _, l := range h.Lines() {
		b.WriteString("// \t" + l + "\n")
	}
	b.WriteString("// source: " + protoPath + "\n\n")
	b.WriteString("import * as pb from \"@bufbuild/protobuf\";\n")
	b.WriteString("import * as ev from " + tsStr(params.eventsImport) + ";\n")
	mods := make([]string, 0, len(g.imports))
	for m := range g.imports {
		mods = append(mods, m)
	}
	sort.Strings(mods)
	for _, m := range mods {
		var types, vals []string
		for n, isType := range g.imports[m] {
			if isType {
				types = append(types, n)
			} else {
				vals = append(vals, n)
			}
		}
		sort.Strings(types)
		sort.Strings(vals)
		if len(vals) > 0 {
			fmt.Fprintf(&b, "import { %s } from %s;\n", strings.Join(vals, ", "), tsStr(m))
		}
		if len(types) > 0 {
			fmt.Fprintf(&b, "import type { %s } from %s;\n", strings.Join(types, ", "), tsStr(m))
		}
	}
	b.WriteString("\n")
	b.WriteString(g.body.String())

	fmt.Fprintf(&b, "/** %s publishes and listens on the event channels declared in\n * %s. */\n", bus, protoPath)
	fmt.Fprintf(&b, "export class %s {\n", bus)
	b.WriteString("  readonly core: ev.Core;\n\n")
	b.WriteString("  constructor(backend: ev.Backend, opts?: ev.CoreOptions) {\n    this.core = new ev.Core(backend, opts);\n  }\n\n")
	b.WriteString("  /** The (channel, group) pairs this bus listens on. Pass them to the control plane. */\n")
	b.WriteString("  subscriptions(): ev.Subscription[] {\n    return this.core.subscriptions();\n  }\n")
	b.WriteString(g.methods.String())
	b.WriteString("}\n")
	return b.String(), nil
}

func (g *tsGen) claim(name, what string) error {
	if prev, ok := g.taken[name]; ok && prev != what {
		return fmt.Errorf("generated name %s (%s) collides with %s; rename the channel", name, what, prev)
	}
	g.taken[name] = what
	return nil
}

// ref imports an identifier from module and claims it.
func (g *tsGen) ref(r tsRef, _ string) (string, error) {
	if err := g.claim(r.name, "import "+r.name+" from "+r.module); err != nil {
		return "", err
	}
	m := g.imports[r.module]
	if m == nil {
		m = map[string]bool{}
		g.imports[r.module] = m
	}
	if prev, ok := m[r.name]; !ok || prev { // a value use wins over a type use
		m[r.name] = r.typ
	}
	return r.name, nil
}

// tsLocal is the name protoc-gen-es gives a message or enum: the full
// name without the package, nesting joined by "_".
func tsLocal(d protoreflect.Descriptor) string {
	n := string(d.FullName())
	if pkg := string(d.ParentFile().Package()); pkg != "" {
		n = strings.TrimPrefix(n, pkg+".")
	}
	return strings.ReplaceAll(n, ".", "_")
}

// modulePath is the import specifier for the code protoc-gen-es wrote
// for file fd, as seen from the events file.
func (g *tsGen) modulePath(fd protoreflect.FileDescriptor) string {
	p := fd.Path()
	if strings.HasPrefix(p, "google/protobuf/") {
		return "@bufbuild/protobuf/wkt"
	}
	target := strings.TrimSuffix(p, ".proto") + "_pb"
	rel, err := filepath.Rel(g.dir, target)
	if err != nil {
		rel = target
	}
	rel = filepath.ToSlash(rel)
	if !strings.HasPrefix(rel, ".") {
		rel = "./" + rel
	}
	return rel + g.params.importExt
}

// msgType imports the type of message md; msgSchema its schema value.
func (g *tsGen) msgType(md protoreflect.MessageDescriptor, what string) (string, error) {
	return g.ref(tsRef{module: g.modulePath(md.ParentFile()), name: tsLocal(md), typ: true}, what)
}

func (g *tsGen) msgSchema(md protoreflect.MessageDescriptor, what string) (string, error) {
	return g.ref(tsRef{module: g.modulePath(md.ParentFile()), name: tsLocal(md) + "Schema"}, what)
}

// fieldType is the TS type of a singular oneof field's value.
func (g *tsGen) fieldType(fd protoreflect.FieldDescriptor, what string) (string, error) {
	switch fd.Kind() {
	case protoreflect.MessageKind, protoreflect.GroupKind:
		return g.msgType(fd.Message(), what)
	case protoreflect.EnumKind:
		return g.ref(tsRef{module: g.modulePath(fd.Enum().ParentFile()), name: tsLocal(fd.Enum()), typ: true}, what)
	case protoreflect.BoolKind:
		return "boolean", nil
	case protoreflect.StringKind:
		return "string", nil
	case protoreflect.BytesKind:
		return "Uint8Array", nil
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind,
		protoreflect.Uint32Kind, protoreflect.Fixed32Kind, protoreflect.FloatKind, protoreflect.DoubleKind:
		return "number", nil
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
		protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "bigint", nil
	}
	return "", fmt.Errorf("unhandled field kind %s", fd.Kind())
}

// tsCamel is protobuf-es's protoCamelCase, the property name of a
// field or oneof: "order_id" -> "orderId".
func tsCamel(s string) string {
	var b strings.Builder
	capNext := false
	for _, r := range s {
		switch {
		case r == '_':
			capNext = true
		case r >= '0' && r <= '9':
			b.WriteRune(r)
			capNext = false
		default:
			if capNext {
				r = unicode.ToUpper(r)
				capNext = false
			}
			b.WriteRune(r)
		}
	}
	return b.String()
}

// tsBusName: orders/v1/orders.proto -> OrdersBus.
func tsBusName(protoPath string) string {
	base := strings.TrimSuffix(path.Base(protoPath), ".proto")
	var b strings.Builder
	up := true
	for _, r := range base {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	if b.Len() == 0 || unicode.IsDigit(rune(b.String()[0])) {
		return "Events" + b.String() + "Bus"
	}
	return b.String() + "Bus"
}

func endIf(last bool, s string) string {
	if last {
		return s
	}
	return ""
}

func tsStr(s string) string { return fmt.Sprintf("%q", s) }

func tsSegName(name string) string {
	c := tsCamel(name)
	return strings.ToLower(c[:1]) + c[1:]
}

const handlerRet = "Promise<void> | void"

func (g *tsGen) channel(c *Channel) error {
	N := upperFirst(c.Name)
	v := lowerFirst(N)
	chVar, segFn, subFn := v+"Channel", v+"Segments", v+"FromSegments"
	subjectT := N + "Subject"
	pub, on := "publish"+N, "on"+N
	if err := g.claim(chVar, "channel "+c.Key); err != nil {
		return err
	}
	for _, n := range []string{segFn, subFn, subjectT} {
		if err := g.claim(n, "channel "+c.Key); err != nil {
			return err
		}
	}

	var fields, toArr, fromArr []string
	seen := map[string]bool{}
	for i, s := range c.Pattern.Segments() {
		n := tsSegName(s.Name)
		if seen[n] {
			return fmt.Errorf("channel %s: segments name the same TypeScript property %s", c.Key, n)
		}
		seen[n] = true
		fields = append(fields, n+": string")
		toArr = append(toArr, "s."+n)
		fromArr = append(fromArr, fmt.Sprintf("%s: v[%d] as string", n, i))
	}
	pat := c.Pattern.String()
	w := &g.body
	fmt.Fprintf(w, "const %s = ev.channel(%s, %s);\n\n", chVar, tsStr(c.Key), tsStr(pat))
	fmt.Fprintf(w, "/** Wildcard segments of a subject on channel %s (pattern %q). */\n", c.Key, pat)
	if len(fields) == 0 {
		fmt.Fprintf(w, "export type %s = Record<string, never>;\n", subjectT)
		fmt.Fprintf(w, "const %s = (_s: %s): string[] => [];\n", segFn, subjectT)
		fmt.Fprintf(w, "const %s = (_v: string[]): %s => ({});\n\n", subFn, subjectT)
	} else {
		fmt.Fprintf(w, "export type %s = { %s };\n", subjectT, strings.Join(fields, "; "))
		fmt.Fprintf(w, "const %s = (s: %s): string[] => [%s];\n", segFn, subjectT, strings.Join(toArr, ", "))
		fmt.Fprintf(w, "const %s = (v: string[]): %s => ({ %s });\n\n", subFn, subjectT, strings.Join(fromArr, ", "))
	}

	what := "channel " + c.Key
	switch c.Kind {
	case KindPlain:
		return g.plainOrWhole(c, N, chVar, segFn, subFn, subjectT, pub, on, what)
	case KindOneof:
		return g.oneof(c, N, chVar, segFn, subFn, subjectT, pub, on, what)
	case KindUnion:
		return g.union(c, N, chVar, segFn, subFn, subjectT, pub, on, what)
	}
	return nil
}

// plainOrWhole writes the publish method and the whole-message listen
// method (onX for plain, onXMessage for oneof).
func (g *tsGen) plainOrWhole(c *Channel, N, chVar, segFn, subFn, subjectT, pub, on, what string) error {
	typ, err := g.msgType(c.Message, what)
	if err != nil {
		return err
	}
	schema, err := g.msgSchema(c.Message, what)
	if err != nil {
		return err
	}
	fqn := tsStr(string(c.Message.FullName()))
	m := &g.methods
	fmt.Fprintf(m, "\n  /** Publishes msg on channel %s. */\n", c.Key)
	fmt.Fprintf(m, "  %s(subject: %s, msg: pb.MessageInitShape<typeof %s>, opts?: ev.PublishOptions): Promise<void> {\n", pub, subjectT, schema)
	fmt.Fprintf(m, "    return this.core.publish(%s, %s(subject), %s, pb.toBinary(%s, pb.create(%s, msg)), opts);\n  }\n", chVar, segFn, fqn, schema, schema)
	listen := on
	if c.Kind == KindOneof {
		listen = on + "Message"
	}
	fmt.Fprintf(m, "\n  /**\n   * Listens on channel %s as group. Subscribers sharing a group share\n   * its messages. Resolving acks the message; throwing redelivers it.\n   */\n", c.Key)
	fmt.Fprintf(m, "  %s(\n    group: string,\n    h: (subject: %s, msg: %s, raw: ev.Message) => %s,\n    opts?: ev.SubscribeOptions,\n  ): Promise<ev.Stop> {\n", listen, subjectT, typ, handlerRet)
	fmt.Fprintf(m, "    return this.core.subscribe(\n      %s,\n      group,\n      (seg, raw) => {\n", chVar)
	fmt.Fprintf(m, "        const t = ev.messageType(raw);\n        if (t !== \"\" && t !== %s) {\n          this.core.skip(%s, raw, %s);\n          return;\n        }\n", fqn, chVar, tsStr("not "+string(c.Message.FullName())))
	fmt.Fprintf(m, "        return h(%s(seg), pb.fromBinary(%s, raw.data), raw);\n      },\n      opts,\n    );\n  }\n", subFn, schema)
	return nil
}

func (g *tsGen) oneof(c *Channel, N, chVar, segFn, subFn, subjectT, pub, on, what string) error {
	if err := g.plainOrWhole(c, N, chVar, segFn, subFn, subjectT, pub, on, what); err != nil {
		return err
	}
	handlers := N + "Handlers"
	if err := g.claim(handlers, what); err != nil {
		return err
	}
	typ, _ := g.msgType(c.Message, what)
	oneofProp := tsCamel(string(c.Oneof.Name()))
	w := &g.body
	fmt.Fprintf(w, "/**\n * Handles each case of %s.%s. A missing handler acks that case. unknown\n * gets a message with no case set; a missing one acks it.\n */\n", c.Message.Name(), c.Oneof.Name())
	fmt.Fprintf(w, "export type %s = {\n", handlers)
	fields := c.Oneof.Fields()
	names := map[string]bool{"unknown": true}
	type cs struct{ prop string }
	var cases []cs
	for i := 0; i < fields.Len(); i++ {
		fd := fields.Get(i)
		prop := tsCamel(string(fd.Name()))
		if names[prop] {
			return fmt.Errorf("channel %s: oneof case %s maps to TypeScript name %s, which the handler type uses", c.Key, fd.Name(), prop)
		}
		names[prop] = true
		ft, err := g.fieldType(fd, what)
		if err != nil {
			return fmt.Errorf("channel %s: %w", c.Key, err)
		}
		fmt.Fprintf(w, "  %s?: (subject: %s, msg: %s, raw: ev.Message) => %s;\n", prop, subjectT, ft, handlerRet)
		cases = append(cases, cs{prop})
	}
	fmt.Fprintf(w, "  unknown?: (subject: %s, msg: %s, raw: ev.Message) => %s;\n};\n\n", subjectT, typ, handlerRet)

	m := &g.methods
	fmt.Fprintf(m, "\n  /**\n   * Listens on channel %s as group and calls the handler for the\n   * message's %s case.\n   */\n", c.Key, c.Oneof.Name())
	fmt.Fprintf(m, "  %s(group: string, h: %s, opts?: ev.SubscribeOptions): Promise<ev.Stop> {\n", on, handlers)
	fmt.Fprintf(m, "    return this.%sMessage(\n      group,\n      (subject, msg, raw) => {\n        switch (msg.%s.case) {\n", on, oneofProp)
	for _, k := range cases {
		fmt.Fprintf(m, "          case %s:\n            return h.%s?.(subject, msg.%s.value, raw);\n", tsStr(k.prop), k.prop, oneofProp)
	}
	fmt.Fprintf(m, "        }\n        if (h.unknown) return h.unknown(subject, msg, raw);\n        this.core.skip(%s, raw, \"no case set, or no handler for it\");\n      },\n      opts,\n    );\n  }\n", chVar)
	return nil
}

func (g *tsGen) union(c *Channel, N, chVar, segFn, subFn, subjectT, pub, on, what string) error {
	event, eventInit, handlers, decode := N+"Event", N+"EventInit", N+"Handlers", "decode"+N+"Event"
	for _, n := range []string{event, eventInit, handlers, decode} {
		if err := g.claim(n, what); err != nil {
			return err
		}
	}
	type member struct {
		fqn, name, typ, schema string
	}
	var ms []member
	seen := map[string]bool{"unknown": true}
	for _, md := range c.Members {
		typ, err := g.msgType(md, what)
		if err != nil {
			return err
		}
		schema, err := g.msgSchema(md, what)
		if err != nil {
			return err
		}
		if seen[typ] {
			return fmt.Errorf("channel %s: member %s maps to TypeScript name %s, which the handler type uses", c.Key, md.FullName(), typ)
		}
		seen[typ] = true
		ms = append(ms, member{fqn: tsStr(string(md.FullName())), name: typ, typ: typ, schema: schema})
	}

	w := &g.body
	fmt.Fprintf(w, "/** A message channel %s carries, tagged with its proto full name. */\n", c.Key)
	fmt.Fprintf(w, "export type %s =\n", event)
	for i, m := range ms {
		fmt.Fprintf(w, "  | { type: %s; value: %s }%s\n", m.fqn, m.typ, endIf(i == len(ms)-1, ";"))
	}
	w.WriteString("\n")
	fmt.Fprintf(w, "/** %s with each value as a message or its init object. */\n", event)
	fmt.Fprintf(w, "export type %s =\n", eventInit)
	for i, m := range ms {
		fmt.Fprintf(w, "  | { type: %s; value: pb.MessageInitShape<typeof %s> }%s\n", m.fqn, m.schema, endIf(i == len(ms)-1, ";"))
	}
	w.WriteString("\n")
	fmt.Fprintf(w, "/**\n * Handles each message type of channel %s. A missing handler acks that\n * type. unknown gets a type this code does not know; a missing one acks it.\n */\n", c.Key)
	fmt.Fprintf(w, "export type %s = {\n", handlers)
	for _, m := range ms {
		fmt.Fprintf(w, "  %s?: (subject: %s, msg: %s, raw: ev.Message) => %s;\n", m.name, subjectT, m.typ, handlerRet)
	}
	fmt.Fprintf(w, "  unknown?: (subject: %s, raw: ev.Message) => %s;\n};\n\n", subjectT, handlerRet)
	fmt.Fprintf(w, "function %s(raw: ev.Message): %s | undefined {\n  switch (ev.messageType(raw)) {\n", decode, event)
	for _, m := range ms {
		fmt.Fprintf(w, "    case %s:\n      return { type: %s, value: pb.fromBinary(%s, raw.data) };\n", m.fqn, m.fqn, m.schema)
	}
	w.WriteString("  }\n  return undefined;\n}\n\n")

	x := &g.methods
	fmt.Fprintf(x, "\n  /** Publishes event on channel %s. */\n", c.Key)
	fmt.Fprintf(x, "  %s(subject: %s, event: %s, opts?: ev.PublishOptions): Promise<void> {\n    switch (event.type) {\n", "publish"+N, subjectT, eventInit)
	for _, m := range ms {
		fmt.Fprintf(x, "      case %s:\n        return this.core.publish(%s, %s(subject), event.type, pb.toBinary(%s, pb.create(%s, event.value)), opts);\n", m.fqn, chVar, segFn, m.schema, m.schema)
	}
	fmt.Fprintf(x, "    }\n  }\n")
	fmt.Fprintf(x, "\n  /**\n   * Listens on channel %s as group. h is a map with one handler per type,\n   * or one function that gets every known type as a tagged event. One\n   * consumer per (channel, group) carries every type. Resolving acks;\n   * throwing redelivers.\n   */\n", c.Key)
	fmt.Fprintf(x, "  %s(\n    group: string,\n    h: %s | ((subject: %s, event: %s, raw: ev.Message) => %s),\n    opts?: ev.SubscribeOptions,\n  ): Promise<ev.Stop> {\n", on, handlers, subjectT, event, handlerRet)
	fmt.Fprintf(x, "    return this.core.subscribe(\n      %s,\n      group,\n      (seg, raw) => {\n        const subject = %s(seg);\n        const e = %s(raw);\n", chVar, subFn, decode)
	fmt.Fprintf(x, "        if (!e) {\n          if (typeof h !== \"function\" && h.unknown) return h.unknown(subject, raw);\n          this.core.skip(%s, raw, \"no handler for this type\");\n          return;\n        }\n", chVar)
	fmt.Fprintf(x, "        if (typeof h === \"function\") return h(subject, e, raw);\n        switch (e.type) {\n")
	for _, m := range ms {
		fmt.Fprintf(x, "          case %s:\n            return h.%s?.(subject, e.value, raw);\n", m.fqn, m.name)
	}
	fmt.Fprintf(x, "        }\n      },\n      opts,\n    );\n  }\n")
	return nil
}
