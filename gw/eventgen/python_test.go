// Captured from betterproto2_compiler 0.10.1 casing.pascal_case /
// safe_snake_case (see betterprotoPin).
func TestPythonCasing(t *testing.T) {
	for _, c := range [][3]string{
		{"OrderShipped", "OrderShipped", "order_shipped"},
		{"HTTPEvent", "HttpEvent", "http_event"},
		{"orderId", "OrderId", "order_id"},
		{"order_id", "OrderId", "order_id"},
		{"P1", "P1", "p_1"},
		{"from", "From", "from_"},
		{"camelCase", "CamelCase", "camel_case"},
		{"fooBar2", "FooBar2", "foo_bar_2"},
		{"HTTPCode", "HttpCode", "http_code"},
		{"snake_msg", "SnakeMsg", "snake_msg"},
		{"ABC", "Abc", "abc"},
		{"aB", "AB", "a_b"},
		{"a1b", "A1B", "a1b"},
		{"IPv4Addr", "IPv4Addr", "i_pv_4_addr"},
		{"XMLHttpRequest2x", "XmlHttpRequest2X", "xml_http_request_2x"},
		{"in", "In", "in_"},
		{"None", "None", "none"},
		{"X_Y", "XY", "X_Y"},
		{"OAuth2Token", "OAuth2Token", "o_auth_2_token"},
		{"userID", "UserId", "user_id"},
		{"Foo_Bar", "FooBar", "Foo_Bar"},
		{"a__b", "AB", "a__b"},
		{"OuterInner", "OuterInner", "outer_inner"},
		{"Order2Event", "Order2Event", "order_2_event"},
		{"e2eTest", "E2ETest", "e_2e_test"},
		{"getHTTPResponseCode", "GetHttpResponseCode", "get_http_response_code"},
	} {
		if got := pyPascalCase(c[0]); got != c[1] {
			t.Errorf("pyPascalCase(%q) = %q, want %q", c[0], got, c[1])
		}
		if got := pySafeSnakeCase(c[0]); got != c[2] {
			t.Errorf("pySafeSnakeCase(%q) = %q, want %q", c[0], got, c[2])
		}
	}
}

func pyEmit(t *testing.T, body string) (map[string]string, error) {
	t.Helper()
	dir := writeProtos(t, map[string]string{"shop.proto": header + body})
	out := t.TempDir()
	written, err := Generate(context.Background(), Config{
		Lang: "python-events", Out: out, ImportPaths: []string{dir}, Files: []string{"shop.proto"},
		GwagVersion: "(devel)",
	})
	if err != nil {
		return nil, err
	}
	files := map[string]string{}
	for _, w := range written {
		files[w] = pyReadFile(t, out+"/"+w)
	}
	return files, nil
}

