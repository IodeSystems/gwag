func TestPythonEmitErrors(t *testing.T) {
	for name, tc := range map[string]struct{ body, want string }{
		"segment names collide": {`
message A { option (gwag.ps.v1.binding) = { name: "A", pattern: "a.{orderId}.{order_id}" }; }`,
			"same Python field order_id"},
		"message named like an import": {`
message Callable { option (gwag.ps.v1.binding) = { name: "Callable", pattern: "a" }; }`,
			"collides"},
		"channel collides with a message": {`
message AEvent {}
message A { option (gwag.ps.v1.binding) = { name: "A", pattern: "a" }; }
message B { option (gwag.ps.v1.binding) = { name: "A", pattern: "a" }; }`,
			"collides with message shop.v1.AEvent"},
		"handler keyword taken": {`
message A { option (gwag.ps.v1.binding) = { name: "A", pattern: "a" }; oneof o { string unknown = 1; string x = 2; } }`,
			"handler keyword"},
		"channels differ in case only": {`
message A { option (gwag.ps.v1.binding) = { name: "Order", pattern: "a" }; }
message B { option (gwag.ps.v1.binding) = { name: "ORDER", pattern: "b" }; }`,
			"collides"},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := pyEmit(t, tc.body)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("err = %v, want it to contain %q", err, tc.want)
			}
		})
	}
}

