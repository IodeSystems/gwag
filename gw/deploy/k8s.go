// Kubernetes: plain YAML, no Helm. A StatefulSet gives each node a
// stable name (gwag-0.gwag-peers) and its own PersistentVolumeClaim.
//
// podManagementPolicy is Parallel, not OrderedReady: a node with
// --nats-peer stays "starting" (503) until it has a meta leader, which
// needs a second node. Under OrderedReady pod 0 would never become
// ready and pod 1 would never start. Parallel affects scaling only;
// updates still go one pod at a time, each waiting for readiness.
//
// The headless Service has publishNotReadyAddresses so peers resolve
// before they pass readiness. Every pod lists all N nodes, itself
// included: one pod template cannot differ per pod, and NATS drops a
// route to itself (measured: 3 nodes, each listing all 3, formed
// size=3).
//
// No preStop hook: the image has no shell, and SIGTERM already runs
// the drain (health flips to 503, --shutdown-delay, close).
const k8sNamespaceTmpl = `apiVersion: v1
kind: Namespace
metadata:
  name: {{.Namespace}}
`

const k8sSecretTmpl = `# Admin token. Do not commit.
apiVersion: v1
kind: Secret
metadata:
  name: gwag-admin
  namespace: {{.Namespace}}
type: Opaque
stringData:
  token: "{{.Token}}"
`

