func genK8s(s Spec) ([]File, error) {
	var peers []string
	if s.Replicas > 1 {
		for i := 0; i < s.Replicas; i++ {
			peers = append(peers, fmt.Sprintf("gwag-%d.gwag-peers.%s.svc:%d", i, s.Namespace, NATSCluster))
		}
	}
	args := nodeArgs("$(POD_NAME)", peers)
	pull := "IfNotPresent"
	if s.Platform == Minikube {
		pull = "Never"
	}
	data := map[string]any{
		"Platform": s.Platform, "Replicas": s.Replicas, "Namespace": s.Namespace,
		"Image": s.Image, "PullPolicy": pull, "Storage": s.Storage, "Token": s.Token,
		"Args": yamlList("            ", args), "Grace": StopGraceSeconds,
		"HTTP": HTTPPort, "CP": CPPort, "NATSClient": NATSClient, "NATSCluster": NATSCluster,
	}
	render := func(name, tmpl string) ([]byte, error) {
		var buf bytes.Buffer
		err := template.Must(template.New(name).Parse(tmpl)).Execute(&buf, data)
		return buf.Bytes(), err
	}
	var files []File
	for _, f := range []struct {
		path, tmpl string
		mode       uint32
	}{
		{"namespace.yaml", k8sNamespaceTmpl, 0o644},
		{"gwag.yaml", k8sTmpl, 0o644},
		{"secrets/secret.yaml", k8sSecretTmpl, 0o600},
	} {
		b, err := render(f.path, f.tmpl)
		if err != nil {
			return nil, err
		}
		files = append(files, File{Path: f.path, Mode: f.mode, Data: b})
	}
	return append(files, secretsGitignore()), nil
}
