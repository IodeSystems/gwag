package deploy

import (
	"bytes"
	"fmt"
	"text/template"
)

// Compose: one service per node (own volume, own stable service name),
// no replicas: field. Service names are the DNS names peers dial on
// the compose network. Published ports are bound to Spec.Bind.
//
// The token goes in an env_file, not a compose "secrets:" file: a
// file secret keeps the host file's mode, and a 0600 file owned by
// the host user is unreadable to the non-root container user.
const composeTmpl = `# Generated by gwag deploy export. Run: docker compose up -d
# Nodes: {{.Replicas}}. Host ports: HTTP {{.HTTPBase}}, control plane {{.CPBase}}, NATS client {{.NATSBase}} (+1 per node).
name: gwag
services:
{{- range .Nodes}}
  {{.Name}}:
    image: {{.Image}}
    restart: unless-stopped
    command:
{{.Command}}
    env_file: ./secrets/gwag.env
    ports:
      - "{{$.Bind}}:{{.HTTP}}:{{$.ContainerHTTP}}"
      - "{{$.Bind}}:{{.CP}}:{{$.ContainerCP}}"
      - "{{$.Bind}}:{{.NATS}}:{{$.ContainerNATS}}"
    volumes:
      - {{.Name}}-data:/data
    stop_grace_period: {{$.Grace}}s
    healthcheck:
      test: ["CMD", "/gwag", "probe", "http://localhost:{{$.ContainerHTTP}}/api/health"]
      interval: 5s
      timeout: 3s
      retries: 3
      start_period: 60s
{{- end}}
volumes:
{{- range .Nodes}}
  {{.Name}}-data:
{{- end}}
`

type composeNode struct {
	Name, Image, Command string
	HTTP, CP, NATS       int
}

func genCompose(s Spec) ([]File, error) {
	var nodes []composeNode
	for i := 1; i <= s.Replicas; i++ {
		var peers []string
		if s.Replicas > 1 {
			for j := 1; j <= s.Replicas; j++ {
				if j != i {
					peers = append(peers, fmt.Sprintf("gwag-%d:%d", j, NATSCluster))
				}
			}
		}
		name := fmt.Sprintf("gwag-%d", i)
		nodes = append(nodes, composeNode{
			Name:    name,
			Image:   s.Image,
			Command: yamlList("      ", nodeArgs(name, peers)),
			HTTP:    s.HTTPBase + i - 1,
			CP:      s.CPBase + i - 1,
			NATS:    s.NATSBase + i - 1,
		})
	}
	var buf bytes.Buffer
	err := template.Must(template.New("compose").Parse(composeTmpl)).Execute(&buf, map[string]any{
		"Replicas": s.Replicas, "HTTPBase": s.HTTPBase, "CPBase": s.CPBase, "NATSBase": s.NATSBase,
		"Nodes": nodes, "Bind": s.Bind, "Grace": StopGraceSeconds,
		"ContainerHTTP": HTTPPort, "ContainerCP": CPPort, "ContainerNATS": NATSClient,
	})
	if err != nil {
		return nil, err
	}
	return []File{
		{Path: "docker-compose.yaml", Mode: 0o644, Data: buf.Bytes()},
		{Path: "secrets/gwag.env", Mode: 0o600, Data: []byte("GWAG_ADMIN_TOKEN=" + s.Token + "\n")},
		secretsGitignore(),
	}, nil
}
