#!/usr/bin/env bash
# Regenerate gen/ from the gateway's exported proto.
#
#   GATEWAY=http://localhost:8080 ./gen.sh
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd ../../.. && pwd)"
GATEWAY="${GATEWAY:-http://localhost:8080}"
PKG="github.com/iodesystems/gwag/v2/examples/clients/go-proto"
export PATH="$ROOT/.bin:$HOME/go/bin:$PATH"

for tool in protoc protoc-gen-go protoc-gen-go-grpc; do
  command -v "$tool" >/dev/null || { echo "missing $tool (see AGENTS.md, Proto Generation)" >&2; exit 1; }
done

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# The export is a binary FileDescriptorSet, not .proto text.
curl -fsS "$GATEWAY/api/schema/proto?service=greeter,library" -o "$tmp/gateway.fds"

rm -rf gen
mkdir gen
# --descriptor_set_in reads the files from the set; no .proto on disk.
# The M options point each file at this module instead of the go_package
# the services declare.
protoc --descriptor_set_in="$tmp/gateway.fds" \
  --go_out=gen --go-grpc_out=gen \
  --go_opt="module=$PKG/gen" --go-grpc_opt="module=$PKG/gen" \
  --go_opt="Mgreeter.proto=$PKG/gen/greeter/v1;greeterv1" \
  --go-grpc_opt="Mgreeter.proto=$PKG/gen/greeter/v1;greeterv1" \
  --go_opt="Mlibrary.proto=$PKG/gen/library/v1;libraryv1" \
  --go-grpc_opt="Mlibrary.proto=$PKG/gen/library/v1;libraryv1" \
  greeter.proto library.proto

cat > gen/README.md <<'EOM'
Generated by ../gen.sh from the gateway's /api/schema/proto export.
Do not edit. Run ../gen.sh to regenerate.
EOM
echo "generated:"
find gen -name '*.go' | sort
